"""Build the release-candidate PDFs (M6) with the repository's builder, ``market.report.render_pdf``.

Outputs: ``research/paper/manuscript.pdf``, ``research/paper/supplementary.pdf`` and
``research/experiments/EXP-00N/report.pdf``. Also regenerates ``research/paper/manuscript.tex``
(pandoc, LaTeX writer, the two header lines kept). With ``--png DIR`` every page of every PDF is
also rendered to PNG in DIR (for visual inspection; DIR should be outside the repository).

Usage: .venv/bin/python scripts/build_pdfs.py [--png DIR] [--ppi 60]
"""

from __future__ import annotations

import argparse
import json
import os
import subprocess
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from market.report import DEFAULT_PANDOC, DEFAULT_TYPST_PY, render_pdf  # noqa: E402

PAPER = ROOT / "research" / "paper"
BIB = PAPER / "references.bib"
TEX_HEADER = ("% SPDX-License-Identifier: LicenseRef-MARKET-NC-Research-1.0\n"
              "% GENERATED by: pandoc -s research/paper/manuscript.md -t latex (pandoc 3.6.3). "
              "Do not edit; edit manuscript.md. Not compiled locally (no TeX, D-003).\n")


def targets() -> list[Path]:
    reports = sorted((ROOT / "research" / "experiments").glob("EXP-*/report.md"))
    return [PAPER / "manuscript.md", PAPER / "supplementary.md", *reports]


def write_tex() -> None:
    pandoc = os.environ.get("MARKET_PANDOC", DEFAULT_PANDOC)
    out = subprocess.run([pandoc, "-s", str(PAPER / "manuscript.md"), "-t", "latex"], check=True,
                         capture_output=True, text=True, cwd=ROOT).stdout
    (PAPER / "manuscript.tex").write_text(TEX_HEADER + out, encoding="utf-8")


def render_png(typ: Path, out_dir: Path, stem: str, ppi: int) -> None:
    typst_py = os.environ.get("MARKET_TYPST_PYTHON", DEFAULT_TYPST_PY)
    code = ("import sys, typst; typst.compile(sys.argv[1], output=sys.argv[2], format='png', "
            "ppi=int(sys.argv[4]), root=sys.argv[3])")
    out_dir.mkdir(parents=True, exist_ok=True)
    subprocess.run([typst_py, "-I", "-c", code, str(typ), str(out_dir / f"{stem}-{{p}}.png"), str(typ.parent), str(ppi)],
                   check=True, capture_output=True, text=True)


def main(argv: list[str] | None = None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--png", type=Path)
    ap.add_argument("--ppi", type=int, default=60)
    a = ap.parse_args(argv)
    write_tex()
    built = {}
    for md in targets():
        pdf = render_pdf(md, bibliography=BIB, keep_typ=a.png is not None)
        stem = md.parent.name if md.name == "report.md" else md.stem
        if a.png is not None:
            typ = md.with_suffix(".typ")
            try:
                render_png(typ, a.png, stem, a.ppi)
            finally:
                typ.unlink(missing_ok=True)
        built[str(pdf.relative_to(ROOT))] = pdf.stat().st_size
    print(json.dumps(built, indent=1))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
