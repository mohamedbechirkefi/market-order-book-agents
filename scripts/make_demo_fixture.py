"""Write the small engine fixture that the demo's sandbox port is tested against (M5).

Runs the Python research engine (src/market) on a handful of short configurations with
development seeds (never the confirmatory seeds 1001..1030) and records, per case, the full
mid-price series, checksums of the other recorded series, the event counts, the final
balances, the final book and the metrics. The vitest suite demo/src/engine/engine.test.ts
compares the TypeScript port with this file. Exploratory tooling check, not a result.

    .venv/bin/python scripts/make_demo_fixture.py
"""

from __future__ import annotations

import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "src"))

from market.config import Composition, SimConfig  # noqa: E402
from market.metrics import compute_metrics  # noqa: E402
from market.rng import STREAM_NAMES, make_streams  # noqa: E402
from market.simulate import simulate  # noqa: E402

OUT = ROOT / "demo" / "src" / "engine" / "fixture.json"
SHORT = dict(steps=4_000, burn_in=1_000, sample_interval=10, extra_vci_intervals=())

CASES = [
    ("A0 all random-order", 11, dict(composition=Composition(ZI=100))),
    ("A1 30 trend followers", 12, dict(composition=Composition(ZI=70, TF=30))),
    ("A3 15 TF and 15 MR", 13, dict(composition=Composition(ZI=70, TF=15, MR=15))),
    ("A4 30 placebo", 14, dict(composition=Composition(ZI=70, PA=30))),
    ("A1 with a sell shock", 15, dict(composition=Composition(ZI=70, TF=30), shock_step=2_500)),
    ("A1 tick 2, low liquidity", 16, dict(composition=Composition(ZI=70, TF=30), tick=2, zi_market_prob=0.35)),
]

METRICS = ("vci", "realised_volatility", "return_acf1", "mean_spread", "mean_depth_at_best", "volume_per_step", "max_drawdown",
           "one_sided_fraction", "n_returns", "n_nonzero_returns", "final_mid")


def checks(a) -> dict:
    xs = [int(v) for v in a]
    return {"sum": sum(xs), "weighted": sum(i * v for i, v in enumerate(xs))}


def main() -> int:
    s = make_streams(7)
    rng = {k: [s[k].uniform() for _ in range(5)] for k in STREAM_NAMES}
    cases = []
    for name, seed, kw in CASES:
        cfg = SimConfig(**SHORT, **kw).validate()
        out = simulate(cfg, seed)
        m, flags = compute_metrics(out)
        d = cfg.to_dict()
        d.pop("extra_vci_intervals")
        cases.append({
            "name": name,
            "seed": seed,
            "config": d,
            "mid": [float(v) for v in out.mid],
            "best_bid": checks(out.best_bid),
            "best_ask": checks(out.best_ask),
            "depth_best": checks(out.depth_best),
            "volume": checks(out.volume),
            "counts": out.counts,
            "final_cash": out.final_cash,
            "final_inventory": out.final_inventory,
            "shock": out.shock,
            "metrics": {k: m[k] for k in METRICS},
            "degenerate": flags["degenerate"],
        })
    doc = {
        "note": "Generated by scripts/make_demo_fixture.py from the Python engine (src/market). Development seeds only; exploratory tooling check, not a result.",
        "rng_seed": 7,
        "rng_first_uniforms": rng,
        "cases": cases,
    }
    OUT.write_text(json.dumps(doc, sort_keys=True, separators=(",", ":")) + "\n")
    print(f"wrote {OUT.relative_to(ROOT)}: {len(cases)} cases")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
